package ru.cherdakmd.chrdkguilds;

/** Результат запроса состава временной группы, не разрешение на PvP или поддержку. */
public enum AdventureGroupRelation {
    /** Оба игрока состоят в одной проверенной временной группе. */
    SAME_GROUP,
    /** Совместное участие не подтверждено при доступном состоянии. */
    DIFFERENT,
    /** Состояние нельзя надёжно проверить: доступ на этой основе не выдавать. */
    UNKNOWN
}
