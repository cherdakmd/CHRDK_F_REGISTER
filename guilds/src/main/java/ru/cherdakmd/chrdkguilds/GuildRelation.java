package ru.cherdakmd.chrdkguilds;

/**
 * Подтверждённое отношение игроков по данным гильдий, без выдачи PvP-прав.
 * При недоступном модуле или ошибке чтения вызывающий обязан считать данные
 * неизвестными и не разрешать доступ на основе предположения об отсутствии войны.
 */
public enum GuildRelation {
    /** Оба игрока состоят в одной гильдии. */
    SAME_GUILD,
    /** Гильдии игроков находятся в активной войне друг с другом. */
    ACTIVE_WAR,
    /** Гильдии различаются или у одного из игроков гильдии нет; активной войны между ними нет. */
    OTHER,
    /** Входные данные или хранилище недоступны; не следует трактовать как OTHER. */
    UNKNOWN
}
