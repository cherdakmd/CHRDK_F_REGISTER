package ru.cherdakmd.chrdkregister.api;

/**
 * Стадия входа игрока, видимая аддонам. Зеркало внутреннего состояния плагина:
 * значения стабильны между минорными версиями, удаляться не будут.
 */
public enum ApiAuthStage {
    /** Проходки нет — игрок полностью заблокирован и ждёт оплаты. */
    NO_PASS,
    /** Проходка есть, но пароль не зарегистрирован — ждём /register. */
    NEEDS_REGISTER,
    /** Ждём ввода пароля (/login). */
    NEEDS_LOGIN,
    /** Пароль принят, ждём код TOTP 2FA. */
    NEEDS_TWO_FACTOR,
    /** Полностью авторизован, играет. */
    AUTHENTICATED
}
