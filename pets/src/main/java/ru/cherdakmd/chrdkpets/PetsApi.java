package ru.cherdakmd.chrdkpets;

import java.util.List;
import java.util.Set;
import java.util.UUID;

/**
 * Публичный API питомцев для других аддонов.
 *
 * <p>Интерфейс намеренно не тянет Bukkit-типы: достижения или стримы могут
 * спросить уровень и настроение питомца по UUID, не завися от сущностей и мира.
 * Регистрация — через {@code ServicesManager}, как у остальных модулей
 * репозитория.</p>
 *
 * <p>Методы заботы возвращают {@code -1}, если забота выключена в конфиге или
 * питомец не найден: так вызывающий код отличает «нет данных» от нуля.</p>
 */
public interface PetsApi {

    /** Зарегистрирован ли питомец (в том числе погибший). */
    boolean isPet(UUID petId);

    /** Уровень питомца; 0 — запись не найдена. */
    int levelOf(UUID petId);

    /** Накопленный опыт; 0 — запись не найдена. */
    long xpOf(UUID petId);

    /** Кличка (пустая строка — не назван); {@code null} — запись не найдена. */
    String nameOf(UUID petId);

    /** Все питомцы игрока, включая погибших. */
    List<UUID> petsOf(UUID ownerId);

    /** Настроение 0..100; -1 — забота выключена или питомец не найден. */
    int moodOf(UUID petId);

    /** Сытость 0..100; -1 — забота выключена или питомец не найден. */
    int satietyOf(UUID petId);

    /** Выученные трюки; пустой набор — трюков нет или питомец не найден. */
    Set<String> tricksOf(UUID petId);

    /** Закрытые достижения; пустой набор — вех нет или питомец не найден. */
    Set<String> achievementsOf(UUID petId);

    /** Топ живых питомцев по опыту (не больше {@code limit}). */
    List<UUID> top(int limit);
}
