package ru.cherdakmd.diamondshop;

/**
 * Целые лоты без «одного алмаза» (7 ноября 2026).
 *
 * <p>Алмаз не делится: копеек и алмазной пыли в экономике нет, поэтому цену
 * скидкой на 0,9 алмаза выразить нельзя. Вместо этого магазин гарантирует, что
 * <b>цена эталонного лота не меньше {@link #MIN_LOT_PRICE} алмазов</b>: если
 * расчёт дал 1, увеличивается <b>количество товара в лоте</b> по ряду
 * {@link #SIZES}, а цена лота пересчитывается из той же удельной цены. Удельная
 * цена за штуку от этого почти не меняется — меняется минимальная партия,
 * в которой сделка вообще имеет смысл.</p>
 *
 * <p>Проверка идёт по консервативной нижней цене ({@code base × minMultiplier}
 * с учётом спреда): при любом запасе товара лот остаётся не дешевле порога.
 * Покупка округляется вверх, продажа вниз — как в {@link WholeTrades}. Бонусы
 * ранга и престижа не применяются к цене вообще: они увеличивают дневной лимит
 * в {@link ShopCapMath}, то есть количество сделок, а не дробную скидку.</p>
 */
final class WholeLotMath {

    /** Минимальная цена целого лота: ниже неё скидка/бонус не выражается. */
    static final int MIN_LOT_PRICE = 2;

    /** Разрешённые размеры лота (совпадают с {@link RecipeEconomy#batch}). */
    static final int[] SIZES = {1, 2, 4, 8, 16, 32, 64, 128, 256, 512, 1024, 2304};

    private WholeLotMath() {
    }

    /**
     * Подбирает минимальный размер лота из {@link #SIZES}, не меньший
     * {@code initialBatch}, при котором и цена покупки, и цена скупки достигают
     * {@link #MIN_LOT_PRICE}. Для товаров без скупки проверяется только покупка.
     *
     * <p>Проверяется <b>внутренняя</b> нижняя цена без тарифа: тариф покупки
     * ({@code 1..100}) только умножает уже целую цену лота, поэтому итоговая
     * покупка никогда не окажется дешевле порога. Так размер лота остаётся
     * независимым от тарифа — прежний контракт «тариф не меняет скупку».</p>
     *
     * @param initialBatch  лот, полученный из рецептурного минимума
     * @param lowerBid      нижняя цена продажи игроком за штуку
     * @param lowerAsk      нижняя цена покупки игроком за штуку (до тарифа)
     * @param sellEnabled   разрешена ли обратная скупка
     * @return подобранный лот, {@code 0} если цена некорректна, или последний
     *         допустимый размер, если даже он не добрал порог
     */
    static int fit(int initialBatch, double lowerBid, double lowerAsk, boolean sellEnabled) {
        if (initialBatch < 1) {
            return 0;
        }
        int last = 0;
        for (int size : SIZES) {
            if (size < initialBatch) {
                continue;
            }
            last = size;
            long ask = WholeTrades.price(lowerAsk, size, true);
            long bid = sellEnabled ? WholeTrades.price(lowerBid, size, false) : MIN_LOT_PRICE;
            if (ask >= MIN_LOT_PRICE && bid >= MIN_LOT_PRICE) {
                return size;
            }
        }
        return last;
    }
}
